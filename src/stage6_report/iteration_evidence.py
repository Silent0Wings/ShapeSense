"""CRISP-DM iteration evidence: why the Quick, Draw! diamonds were dropped.

Iteration 1 (2026-11-08) looped from Modeling/Evaluation back to Data
Preparation: on the VALIDATION split, models trained on the first data
freeze learned Quick, Draw! "diamond" doodles (gemstones, cones, shields)
as a separate visual concept that conflicts with the taxonomy definition
(rhombus without right angles). This module turns the validation outputs of
those runs into a committed record, so the report cites generated numbers.

Validation only: it reads artifacts/stage4/<run>/val_probs.npz and the
validation manifest, never the test split.

    python -m src.stage6_report.iteration_evidence --out docs/crisp_dm
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path

import numpy as np

from src.common.config import class_names, load_default_config, resolve

PERCENT = 100.0
DIAMOND = "diamond"
SKETCH_SOURCE = "quickdraw"
RENDER_SOURCE = "kaggle_reevald"
RECORD_JSON = "iteration_1_quickdraw_diamonds.json"
RECORD_TEX = "iteration_1_quickdraw_diamonds.tex"
MACRO_PREFIX = "IterOne"


def per_class_f1(y: np.ndarray, p: np.ndarray, k: int) -> np.ndarray:
    """F1 per class in points (0-100); 0 for a class absent from both."""
    out = np.zeros(k)
    for c in range(k):
        tp = np.sum((y == c) & (p == c))
        denom = 2 * tp + np.sum((y != c) & (p == c)) + np.sum((y == c) & (p != c))
        out[c] = PERCENT * 2 * tp / denom if denom else 0.0
    return out


def run_evidence(y: np.ndarray, p: np.ndarray, sources: np.ndarray,
                 names: list[str]) -> dict:
    """Diamond metrics of one run from validation labels/predictions/sources."""
    d = names.index(DIAMOND)
    f1 = per_class_f1(y, p, len(names))
    out = {"macro_f1": float(f1.mean()), "diamond_f1": float(f1[d]), "recall_by_source": {}}
    is_d = y == d
    for s in sorted(set(sources[is_d])):
        m = is_d & (sources == s)
        out["recall_by_source"][str(s)] = {"recall": float(PERCENT * np.mean(p[m] == d)),
                                           "n": int(m.sum())}
    qd = is_d & (sources == SKETCH_SOURCE)
    out["quickdraw_diamonds_predicted_as"] = dict(Counter(names[k] for k in p[qd]).most_common())
    return out


def collect(stage4_dir: Path, val_manifest: Path, names: list[str],
            run_dirs: list[Path] | None = None) -> dict:
    with open(val_manifest, encoding="utf-8", newline="") as f:
        source_of = {r["image_id"]: r["source_id"] for r in csv.DictReader(f)}
    runs = {}
    candidates = run_dirs or sorted(p.parent for p in stage4_dir.glob("*/run.json"))
    for run_dir in candidates:
        info = json.loads((run_dir / "run.json").read_text(encoding="utf-8"))
        if not info.get("recipe"):
            continue  # pre-fix recipe (P-54/P-55): not comparable
        z = np.load(run_dir / "val_probs.npz", allow_pickle=True)
        ids = [str(i) for i in z["image_ids"]]
        src = np.array([source_of[i] for i in ids])
        runs[info["run_name"]] = {"arm": info["arm"], "seed": info["seed"],
                                  **run_evidence(z["labels"], z["probs"].argmax(1), src, names)}
    return {"split": "validation", "classes": names, "runs": runs}


def _fmt(x: float) -> str:
    return f"{x:.1f}"


def latex_macros(record: dict) -> str:
    """\\providecommand macros, e.g. \\IterOneAZeroQDRecall for run A0_0."""
    lines = ["% Generated by src/stage6_report/iteration_evidence.py - do not edit."]
    words = {"0": "Zero", "1": "One", "2": "Two"}
    for name, r in record["runs"].items():
        arm, seed = name.split("_")[0], str(name.split("_")[-1])
        key = MACRO_PREFIX + arm.replace("0", "Zero").replace("1", "One") + "Seed" + words.get(seed, seed)
        rs = r["recall_by_source"]
        lines += [
            f"\\providecommand{{\\{key}MacroFone}}{{{_fmt(r['macro_f1'])}}}",
            f"\\providecommand{{\\{key}DiamondFone}}{{{_fmt(r['diamond_f1'])}}}",
            f"\\providecommand{{\\{key}QDRecall}}{{{_fmt(rs.get(SKETCH_SOURCE, {}).get('recall', float('nan')))}}}",
            f"\\providecommand{{\\{key}RenderRecall}}{{{_fmt(rs.get(RENDER_SOURCE, {}).get('recall', float('nan')))}}}",
            f"\\providecommand{{\\{key}QDAsTriangle}}{{{r['quickdraw_diamonds_predicted_as'].get('triangle', 0)}}}",
            f"\\providecommand{{\\{key}QDN}}{{{rs.get(SKETCH_SOURCE, {}).get('n', 0)}}}",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", default="docs/crisp_dm")
    args = parser.parse_args()
    cfg = load_default_config()
    record = collect(resolve(cfg["paths"]["artifacts_dir"]) / "stage4",
                     resolve(cfg["paths"]["splits_dir"]) / "val.csv", class_names(cfg))
    out = resolve(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / RECORD_JSON).write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    (out / RECORD_TEX).write_text(latex_macros(record), encoding="utf-8")
    print(f"wrote {out / RECORD_JSON} ({len(record['runs'])} runs)")


if __name__ == "__main__":
    main()
