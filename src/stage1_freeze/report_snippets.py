"""LaTeX macros with the published Stage 1 counts (plan 34, Stage 6 hand-off).

Written to artifacts/stage1/report_counts.tex and `\\input` by the report,
so the Split paragraph never carries a typed number.
"""

from __future__ import annotations

from pathlib import Path
from typing import Mapping

THOUSANDS_SEPARATOR = "{,}"   # LaTeX thin thousands separator in math mode
FILTER_APPLIED = "applied"
FILTER_PENDING = "not yet applied (review pending)"
FILTER_SUPERSEDED = ("superseded: all Quick, Draw! diamonds are excluded by rule "
                     "(CRISP-DM iteration 1)")


def latex_int(n: int) -> str:
    """12761 -> '12{,}761'."""
    return f"{int(n):,}".replace(",", THOUSANDS_SEPARATOR)


def write_report_counts(path: str | Path, counts: Mapping[str, int], gemstones_removed: int,
                        filter_state: str, n_groups: int, largest_group: int) -> Path:
    """Write \\providecommand macros for the report. counts has train/val/test."""
    total = sum(int(counts[s]) for s in ("train", "val", "test"))
    macros = [
        ("SplitTrain", latex_int(counts["train"])),
        ("SplitVal", latex_int(counts["val"])),
        ("SplitTest", latex_int(counts["test"])),
        ("SplitTotal", latex_int(total)),
        ("GemstonesRemoved", latex_int(gemstones_removed)),
        ("GemstoneFilterState", filter_state),
        ("NearDupGroups", latex_int(n_groups)),
        ("LargestNearDupGroup", latex_int(largest_group)),
    ]
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by Stage 1 (src/stage1_freeze/report_snippets.py). Do not edit."]
    lines += [f"\\providecommand{{\\{name}}}{{{value}}}" for name, value in macros]
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return p
