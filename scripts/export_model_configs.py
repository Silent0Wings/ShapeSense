"""Write one readable config per model from configs/pipeline.yaml.

``python -m scripts.export_model_configs`` writes configs/models/<arm>.yaml with
each model's network, training settings, batch mix, augmentation and generator
ranges after its tuned overrides. pipeline.yaml stays the source of truth, and
a test fails if these files fall out of step with it.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from src.common.config import REPO_ROOT, arm_config, class_names, load_config
from src.stage4_train.model import CONV_KERNEL, CONV_PADDING, POOL_SIZE, build_model, count_params
from src.stage4_train.sampling import batch_composition, clean_count

OUT_DIR = Path(REPO_ROOT) / "configs" / "models"
HEADER = "# Generated by scripts/export_model_configs.py from configs/pipeline.yaml. Do not edit by hand.\n"
ABOUT = {
    "A0": ("Real only", "The control. Trains on real drawings, unchanged."),
    "A1": ("Real + augmented", "Trains on real drawings, every one randomly augmented."),
    "B": ("Real + synthetic", "Trains on augmented real drawings plus computer-generated shapes, also augmented."),
    "A2": ("Full mix", "Trains on unchanged real drawings, augmented real drawings and computer-generated shapes."),
    "P": ("Synthetic pretraining", "Trains on computer-generated shapes first, then continues on augmented real drawings."),
}


def model_config(config: dict, arm: str) -> dict:
    """The full setup of one model, after its tuned overrides."""
    tuned = arm_config(config, arm)
    arm_cfg, train = tuned["arms"][arm], tuned["train"]
    n_classes = len(class_names(tuned))
    batch = int(train["batch_size"])
    real, synthetic = batch_composition(arm_cfg, batch, float(tuned["synthetic_fraction"]))
    clean = clean_count(arm_cfg, batch) if arm_cfg["augment"] else real
    max_epochs = int(train["max_epochs"])
    pretrain_epochs = int(float(arm_cfg.get("pretrain_fraction", 0.0)) * max_epochs)
    dropout, lr = float(arm_cfg["hparams"]["dropout"]), float(arm_cfg["hparams"]["lr"])
    name, about = ABOUT[arm]
    return {
        "model": {"id": arm, "name": name, "about": about},
        "network": {
            "type": "SmallCNN",
            "input": [int(tuned["image_channels"]), int(tuned["image_size"]), int(tuned["image_size"])],
            "block_channels": [int(c) for c in train["channels"]],
            "each_block": [f"Conv {CONV_KERNEL}x{CONV_KERNEL}, padding {CONV_PADDING}", "BatchNorm", "ReLU", f"MaxPool {POOL_SIZE}"],
            "after_blocks": ["Global average pool", "Dropout", "Linear"],
            "classes": n_classes,
            "dropout": dropout,
            "learned_parameters": count_params(build_model(tuned, n_classes, dropout)),
        },
        "training": {
            "optimizer": train["optimizer"],
            "learning_rate": lr,
            "weight_decay": float(train["weight_decay"]),
            "schedule": train["schedule"],
            "batch_size": batch,
            "steps_per_epoch": int(train["steps_per_epoch"]),
            "max_epochs": max_epochs,
            "early_stopping": int(train["early_stopping_patience"]) < max_epochs,
            "kept_epoch": f"best {train['selection_metric']}",
            "seeds": [int(s) for s in tuned["seed_set"]],
            "source_holdout_runs": int(tuned["evaluation"]["loso_seeds"]),
        },
        "batch_mix": {
            "images_per_batch": {"real_unchanged": clean, "real_augmented": real - clean, "synthetic": synthetic},
            "pretraining": {"epochs": pretrain_epochs, "images_per_batch": {"synthetic": batch}} if pretrain_epochs else None,
        },
        "augmentation": {**tuned["augment"], "rotate_limit_deg": tuned["taxonomy"].get("rotate_limit_deg")} if arm_cfg["augment"] else None,
        "generator": tuned["synth"] if arm_cfg["synthetic"] else None,
    }


def main() -> None:
    config = load_config()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for arm in config["arms"]:
        body = yaml.safe_dump(model_config(config, arm), sort_keys=False, default_flow_style=None, width=120, allow_unicode=True)
        (OUT_DIR / f"{arm}.yaml").write_text(HEADER + body, encoding="utf-8", newline="\n")
        print(f"wrote configs/models/{arm}.yaml")


if __name__ == "__main__":
    main()
